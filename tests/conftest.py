WORDS = sorted(set((TWO_LETTER + LONGER).split()))

# A second lexicon that differs by one word, for checkpoint-compatibility tests.
OTHER_WORDS = sorted(set(WORDS) - {"ZOO"})


def write_words(path: Path, words: list[str]) -> Path:
    path.write_text("\n".join(words) + "\n", encoding="utf-8")
    return path


@pytest.fixture(scope="session")
def lexicon_dir(tmp_path_factory) -> Path:
    directory = tmp_path_factory.mktemp("lexicon")
    write_words(directory / "TEST.txt", WORDS)
    write_words(directory / "OTHER.txt", OTHER_WORDS)
    return directory


@pytest.fixture(scope="session")
def engine(lexicon_dir) -> _core.Engine:
    return _core.Engine("TEST", lexicon_dir / "TEST.txt", lexicon_dir / "cache")


@pytest.fixture(scope="session")
def zero_leaves() -> _core.LeaveModel:
    return _core.LeaveModel.zero()


@pytest.fixture(scope="session")
def leaves(engine) -> _core.LeaveModel:
    """Leave values fitted on a few hundred greedy games: small but non-zero, so the static
    ranking (score + leave) differs from score alone."""
    seeds = np.arange(400, dtype=np.uint64) + np.uint64(10_000)
    model, _report = engine.fit_leaves("greedy", _core.LeaveModel.zero(), seeds, 50.0)
    return model


